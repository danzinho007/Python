import random

def tem_tripla(numero_str):
    """Verifica se o número contém 3 dígitos iguais seguidos."""
    for i in range(len(numero_str) - 2):
        if numero_str[i] == numero_str[i+1] == numero_str[i+2]:
            return True
    return False

def gerar_manifestos_aleatorios_ordenados(quantidade, arquivo_saida, ignorar=None):
    if ignorar is None:
        ignorar = set()

    numeros = set()
    
    while len(numeros) < quantidade:
        numero = random.randint(10**18, 10**19 - 1)  # número aleatório de 19 dígitos
        numero_str = str(numero)
        linha = f"download_depot 65800 65801 {numero_str}"
        
        # só adiciona se não tiver tripla e não estiver na blacklist
        if not tem_tripla(numero_str) and linha not in ignorar:
            numeros.add(numero)
    
    # ordenar antes de salvar
    numeros_ordenados = sorted(numeros)

    with open(arquivo_saida, "w") as f:
        for numero in numeros_ordenados:
            f.write(f"download_depot 65800 65801 {numero}\n")

